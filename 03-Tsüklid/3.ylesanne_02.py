# 2. Tingimus i < 5 otsustab, kas tsükkel jätkub.
# 3. Tsükli sisu täidetakse 5 korda (i = 0, 1, 2, 3, 4).
# 4. Pärast tsükli lõppu on i väärtus 5 (siis i < 5 on väär).